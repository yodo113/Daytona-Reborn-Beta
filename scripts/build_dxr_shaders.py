#!/usr/bin/env python3
"""Compile the ray-traced shadow shaders (src/app/gpu/dxr.hlsl and
dxr_shadow.hlsl) to DXIL and write src/app/gpu/dxr_shaders_gen.h, which is
committed: a build needs no shader tools, only changing a shader does.

Direct3D 12 only (DXR), so DXIL only: the Windows SDK's dxc.exe, found on
PATH or in the newest Windows Kits 10 bin folder, or given with --dxc.
"""

import argparse
import glob
import os
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GPU = os.path.join(ROOT, "src", "app", "gpu")
WORK = os.path.join(ROOT, "build", "dxr_shaders")

# source, entry point, profile
ENTRIES = [("dxr.hlsl", "ps_view_z", "ps_6_0"), ("dxr.hlsl", "ps_view_z2", "ps_6_0"), ("dxr.hlsl", "ps_front_z", "ps_6_0"),
           ("dxr.hlsl", "ps_quad_z", "ps_6_0"), ("dxr.hlsl", "ps_shade", "ps_6_0"),
           ("dxr_shadow.hlsl", "cs_shadow", "cs_6_5"), ("dxr_shadow.hlsl", "cs_shafts", "cs_6_5"),
           ("dxr_shadow.hlsl", "cs_shadow_large", "cs_6_5"), ("dxr_shadow.hlsl", "cs_shafts_large", "cs_6_5")]


def find_dxc():
    if shutil.which("dxc"):
        return "dxc"
    kits = sorted(glob.glob(r"C:\Program Files (x86)\Windows Kits\10\bin\10.*\x64\dxc.exe"))
    return kits[-1] if kits else None


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--dxc", default=None)
    args = parser.parse_args()
    dxc = args.dxc or find_dxc()
    if not dxc:
        sys.exit("build_dxr_shaders: dxc.exe not found (Windows SDK)")
    os.makedirs(WORK, exist_ok=True)
    out = ["// Generated by scripts/build_dxr_shaders.py from src/app/gpu/dxr*.hlsl: do not edit.",
           "#pragma once", ""]
    for source, entry, profile in ENTRIES:
        binary = os.path.join(WORK, entry + ".dxil")
        subprocess.run([dxc, "-Qstrip_debug", "-Qstrip_reflect", "-T", profile, "-E", entry,
                        "-Fo", binary, os.path.join(GPU, source)], check=True)
        data = open(binary, "rb").read()
        rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
        out.append(f"static const unsigned char k_{entry}_dxil[] = {{\n    " + ",\n    ".join(rows) + "\n};\n")
    with open(os.path.join(GPU, "dxr_shaders_gen.h"), "w", newline="\n") as f:
        f.write("\n".join(out))
    print("build_dxr_shaders: wrote src/app/gpu/dxr_shaders_gen.h")


if __name__ == "__main__":
    main()
